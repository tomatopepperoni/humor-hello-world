-- updated_at triggers ----------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['llm_providers', 'llm_models', 'prompt_chains', 'terms',
                           'generation_examples', 'allowed_signup_domains', 'whitelisted_emails']
  loop
    execute format('drop trigger if exists touch_updated_at on public.%I', t);
    execute format('create trigger touch_updated_at before update on public.%I
                    for each row execute function public.touch_updated_at()', t);
  end loop;
end $$;


-- 12. Row Level Security --------------------------------------------------------------
do $$
declare t text;
begin
  -- full CRUD for superadmins
  foreach t in array array['llm_providers', 'llm_models', 'terms', 'generation_examples',
                           'allowed_signup_domains', 'whitelisted_emails']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('drop policy if exists "superadmin: full access" on public.%I', t);
    execute format('create policy "superadmin: full access" on public.%I for all to authenticated
                    using (public.is_superadmin()) with check (public.is_superadmin())', t);
  end loop;

  -- read-only for superadmins (written by the SQL editor or by log_generation())
  foreach t in array array['prompt_chains', 'prompt_chain_steps', 'generation_requests', 'llm_responses']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('revoke insert, update, delete on public.%I from authenticated', t);
    execute format('drop policy if exists "superadmin: read" on public.%I', t);
    execute format('create policy "superadmin: read" on public.%I for select to authenticated
                    using (public.is_superadmin())', t);
  end loop;
end $$;

