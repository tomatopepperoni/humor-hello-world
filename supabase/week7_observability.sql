-- 8. generation_requests ----------------------------------------------------------
create table if not exists public.generation_requests (
  id             uuid primary key default gen_random_uuid(),
  user_id        uuid references auth.users (id) on delete set null,
  post_id        uuid,                 -- no FK on purpose: the log outlives a deleted post
  chain_id       bigint references public.prompt_chains (id) on delete set null,
  vibe           text,
  kind           text not null check (kind in ('create', 'more', 'admin', 'backfill')),
  app            text not null default 'caption-app' check (app in ('caption-app', 'admin')),
  status         text not null check (status in ('success', 'failed')),
  prompt         text,
  has_image      boolean not null default false,
  model          text,                 -- the model that answered (null when it failed)
  attempt_count  int not null default 0,
  caption_count  int not null default 0,
  error          text,
  duration_ms    int,
  config_source  text check (config_source in ('database', 'code')),  -- where the prompt/models came from
  started_at     timestamptz not null default now(),
  finished_at    timestamptz,
  created_at     timestamptz not null default now()
);
create index if not exists generation_requests_created_idx on public.generation_requests (created_at desc);
create index if not exists generation_requests_user_idx on public.generation_requests (user_id);
create index if not exists generation_requests_post_idx on public.generation_requests (post_id);


-- 9. llm_responses ----------------------------------------------------------------
create table if not exists public.llm_responses (
  id               bigint generated by default as identity primary key,
  request_id       uuid not null references public.generation_requests (id) on delete cascade,
  attempt          int not null,       -- 1, 2, 3 ... in call order
  round            int not null default 1,
  model            text not null,
  outcome          text not null check (outcome in ('ok', 'unusable', 'http_error', 'blocked', 'empty', 'timeout', 'network')),
  http_status      int,
  latency_ms       int,
  finish_reason    text,
  prompt_tokens    int,
  output_tokens    int,
  thinking_tokens  int,
  total_tokens     int,
  raw_text         text,               -- first 8000 characters of what the model said
  error            text,
  created_at       timestamptz not null default now()
);
create index if not exists llm_responses_request_idx on public.llm_responses (request_id, attempt);
create index if not exists llm_responses_created_idx on public.llm_responses (created_at desc);


