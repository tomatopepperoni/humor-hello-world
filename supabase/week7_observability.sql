-- Week 7: Admin panel with more observability
-- Run this in the Supabase SQL editor (project: humor-joke) AFTER week6_admin.sql
-- (it uses public.is_superadmin()). Safe to re-run: it never drops data, and
-- seed rows are only inserted when they are missing.
--
-- What it adds
--
--   Generation settings (what the caption app sends to Gemini)
--     llm_providers           who serves the model (Google). The API key itself
--                             never lives in the DB, only the env var's name.
--     llm_models              which models to try, in priority order, with
--                             temperature / max output tokens per model
--     prompt_chains           one chain per subway voice (Conductor, ...)
--     prompt_chain_steps      the ordered sections that make up a chain's prompt
--     prompt_chain_mix        which voices the picker offers and their share in
--                             "Surprise me"
--     terms                   NYC / subway / campus vocabulary added to prompts
--     generation_examples     few-shot example captions (seeded with the voice
--                             samples; admins can promote top-voted captions)
--
--   Observability (what actually happened)
--     generation_requests     one row per "write captions" run: who, which voice,
--                             the exact prompt, status, duration, the model that
--                             answered
--     llm_responses           one row per model call inside a run (retries and
--                             fallbacks included): HTTP status, latency, tokens,
--                             finish reason, the raw text, why it was rejected
--     captions.generation_request_id   links every caption to its run
--
--   Access
--     allowed_signup_domains  e.g. columbia.edu, barnard.edu
--     whitelisted_emails      single addresses allowed outside those domains
--
--   Images: posts get superadmin UPDATE/DELETE (and photos-bucket delete), so the
--   admin area can upload, replace and remove photos.
--
-- Security model (same as week 6): the apps use the anon key + the signed-in
-- user's session. Every new table has RLS on. Superadmins can read everything
-- and write what the assignment asks for; normal users can read nothing here
-- directly. The caption app reaches the settings and the logs only through three
-- security-definer functions: generation_config(), voice_mix() and
-- log_generation().


-- 0. shared trigger ------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;


-- 1. llm_providers ---------------------------------------------------------------
create table if not exists public.llm_providers (
  id           bigint generated by default as identity primary key,
  slug         text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name         text not null,
  base_url     text,
  api_key_env  text,                 -- name of the env var that holds the key
  is_active    boolean not null default true,
  notes        text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);


-- 2. llm_models -------------------------------------------------------------------
create table if not exists public.llm_models (
  id                 bigint generated by default as identity primary key,
  provider_id        bigint not null references public.llm_providers (id) on delete restrict,
  model_id           text not null unique,        -- API name, e.g. gemini-3.6-flash
  display_name       text not null,
  priority           int not null default 100,    -- lower is tried first
  is_active          boolean not null default true,
  temperature        numeric(3, 2) not null default 1.0 check (temperature between 0 and 2),
  max_output_tokens  int not null default 8192 check (max_output_tokens between 256 and 65536),
  notes              text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create index if not exists llm_models_priority_idx on public.llm_models (priority, id);


-- 3. prompt_chains ----------------------------------------------------------------
create table if not exists public.prompt_chains (
  id           bigint generated by default as identity primary key,
  slug         text not null unique,              -- same key as captions.vibe
  name         text not null,
  description  text,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);


-- 4. prompt_chain_steps -----------------------------------------------------------
-- The app joins a chain's steps, in order, into one Gemini prompt. A step with a
-- condition is skipped when that input is missing (no photo, no theme, ...).
-- Placeholders: {{theme}} {{context}} {{terms}} {{examples}} {{avoid}} {{count}}
create table if not exists public.prompt_chain_steps (
  id          bigint generated by default as identity primary key,
  chain_id    bigint not null references public.prompt_chains (id) on delete cascade,
  step_order  int not null,
  name        text not null,
  condition   text check (condition in ('has_image', 'has_theme', 'has_context', 'has_terms', 'has_examples', 'has_avoid')),
  template    text not null,
  created_at  timestamptz not null default now(),
  unique (chain_id, step_order)
);


-- 5. prompt_chain_mix -------------------------------------------------------------
create table if not exists public.prompt_chain_mix (
  chain_id    bigint primary key references public.prompt_chains (id) on delete cascade,
  is_enabled  boolean not null default true,      -- offered in the voice picker
  weight      int not null default 20 check (weight between 0 and 100),  -- share in "Surprise me"
  updated_at  timestamptz not null default now(),
  updated_by  uuid references auth.users (id) on delete set null
);

create or replace function public.stamp_mix_update()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  new.updated_by := coalesce(auth.uid(), new.updated_by);
  return new;
end;
$$;

drop trigger if exists stamp_mix_update on public.prompt_chain_mix;
create trigger stamp_mix_update
  before update on public.prompt_chain_mix
  for each row execute function public.stamp_mix_update();


