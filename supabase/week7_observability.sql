-- 15. backfill: one generation_request per earlier caption run ---------------------------
-- Captions written before week 7 carry their prompt and model but no timing, so
-- these rows have kind = 'backfill', no llm_responses and no duration. Runs only once.
do $$
begin
  if not exists (select 1 from public.generation_requests where kind = 'backfill') then
    create temporary table _bf on commit drop as
      select gen_random_uuid() as id, c.post_id, c.user_id, c.prompt, c.model, c.vibe,
             min(c.created_at) as created_at, count(*)::int as n, array_agg(c.id) as caption_ids
      from public.captions c
      where c.generation_request_id is null
        and c.model not like 'admin (%'
      group by c.post_id, c.user_id, c.prompt, c.model, c.vibe;

    insert into public.generation_requests (
      id, user_id, post_id, chain_id, vibe, kind, app, status, prompt, has_image, model,
      attempt_count, caption_count, started_at, finished_at, created_at
    )
    select b.id, b.user_id, b.post_id, ch.id, b.vibe, 'backfill', 'caption-app', 'success', b.prompt,
           coalesce(p.image_url is not null, false), b.model, 0, b.n, b.created_at, b.created_at, b.created_at
    from _bf b
    left join public.posts p on p.id = b.post_id
    left join public.prompt_chains ch on ch.slug = b.vibe;

    update public.captions c
    set generation_request_id = b.id
    from _bf b
    where c.id = any (b.caption_ids);
  end if;
end $$;


