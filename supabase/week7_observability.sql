-- 13. functions the caption app calls -----------------------------------------------------

-- Everything needed to build one prompt for a voice. Called with the user's
-- session from the server. Returns {} pieces as empty arrays when not set up,
-- and the app then falls back to its built-in prompt.
create or replace function public.generation_config(p_vibe text)
returns jsonb
language plpgsql
volatile            -- random() picks
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'sign in first' using errcode = '42501';
  end if;
  return jsonb_build_object(
    'chain', (
      select jsonb_build_object('id', c.id, 'slug', c.slug, 'name', c.name)
      from public.prompt_chains c where c.slug = p_vibe and c.is_active
    ),
    'steps', coalesce((
      select jsonb_agg(jsonb_build_object('order', s.step_order, 'name', s.name,
                                          'condition', s.condition, 'template', s.template)
                       order by s.step_order)
      from public.prompt_chain_steps s
      join public.prompt_chains c on c.id = s.chain_id
      where c.slug = p_vibe and c.is_active
    ), '[]'::jsonb),
    'terms', coalesce((
      select jsonb_agg(jsonb_build_object('term', t.term, 'definition', t.definition))
      from (select term, definition from public.terms where is_active order by random() limit 10) t
    ), '[]'::jsonb),
    'examples', coalesce((
      select jsonb_agg(jsonb_build_object('moment', x.moment, 'caption', x.caption))
      from (
        select e.moment, e.caption
        from public.generation_examples e
        left join public.prompt_chains c on c.id = e.chain_id
        where e.is_active and (e.chain_id is null or c.slug = p_vibe)
        order by random()
        limit 3
      ) x
    ), '[]'::jsonb),
    'models', coalesce((
      select jsonb_agg(jsonb_build_object('model', m.model_id, 'provider', p.slug,
                                          'temperature', m.temperature,
                                          'max_output_tokens', m.max_output_tokens)
                       order by m.priority, m.id)
      from public.llm_models m
      join public.llm_providers p on p.id = m.provider_id
      where m.is_active and p.is_active
    ), '[]'::jsonb)
  );
end;
$$;

-- The voice picker: which voices are on, and their "Surprise me" weight.
create or replace function public.voice_mix()
returns table (slug text, is_enabled boolean, weight int)
language sql
stable
security definer
set search_path = public
as $$
  select c.slug, m.is_enabled and c.is_active, m.weight
  from public.prompt_chain_mix m
  join public.prompt_chains c on c.id = m.chain_id;
$$;

-- One call per caption run, success or failure. The caller can only log runs
-- as themselves; sizes are capped so the log can't be used as free storage.
create or replace function public.log_generation(p_request jsonb, p_responses jsonb default '[]'::jsonb)
returns uuid
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  rid  uuid;
  uid  uuid := auth.uid();
  k    text := coalesce(p_request ->> 'kind', 'create');
  a    text := coalesce(p_request ->> 'app', 'caption-app');
  resp jsonb := coalesce(p_responses, '[]'::jsonb);
begin
  if uid is null then
    raise exception 'sign in first' using errcode = '42501';
  end if;
  if k not in ('create', 'more', 'admin') then k := 'create'; end if;
  if a not in ('caption-app', 'admin') then a := 'caption-app'; end if;
  if (k = 'admin' or a = 'admin') and not public.is_superadmin() then
    k := 'create'; a := 'caption-app';
  end if;
  if jsonb_typeof(resp) <> 'array' then resp := '[]'::jsonb; end if;

  rid := coalesce((p_request ->> 'id')::uuid, gen_random_uuid());

  insert into public.generation_requests (
    id, user_id, post_id, chain_id, vibe, kind, app, status, prompt, has_image, model,
    attempt_count, caption_count, error, duration_ms, config_source, started_at, finished_at
  ) values (
    rid,
    uid,
    (p_request ->> 'post_id')::uuid,
    (select c.id from public.prompt_chains c where c.slug = p_request ->> 'vibe'),
    left(p_request ->> 'vibe', 40),
    k,
    a,
    case when p_request ->> 'status' = 'success' then 'success' else 'failed' end,
    left(p_request ->> 'prompt', 20000),
    coalesce((p_request ->> 'has_image')::boolean, false),
    left(p_request ->> 'model', 100),
    least(jsonb_array_length(resp), 40),
    greatest(0, least(coalesce((p_request ->> 'caption_count')::int, 0), 50)),
    left(p_request ->> 'error', 2000),
    (p_request ->> 'duration_ms')::int,
    case when p_request ->> 'config_source' in ('database', 'code') then p_request ->> 'config_source' end,
    coalesce((p_request ->> 'started_at')::timestamptz, now()),
    now()
  );

  insert into public.llm_responses (
    request_id, attempt, round, model, outcome, http_status, latency_ms, finish_reason,
    prompt_tokens, output_tokens, thinking_tokens, total_tokens, raw_text, error, created_at
  )
  select
    rid,
    coalesce((r ->> 'attempt')::int, ord::int),
    coalesce((r ->> 'round')::int, 1),
    left(coalesce(r ->> 'model', 'unknown'), 100),
    case when r ->> 'outcome' in ('ok', 'unusable', 'http_error', 'blocked', 'empty', 'timeout', 'network')
         then r ->> 'outcome' else 'http_error' end,
    (r ->> 'http_status')::int,
    (r ->> 'latency_ms')::int,
    left(r ->> 'finish_reason', 40),
    (r ->> 'prompt_tokens')::int,
    (r ->> 'output_tokens')::int,
    (r ->> 'thinking_tokens')::int,
    (r ->> 'total_tokens')::int,
    left(r ->> 'raw_text', 8000),
    left(r ->> 'error', 2000),
    coalesce((r ->> 'at')::timestamptz, now())
  from jsonb_array_elements(resp) with ordinality as e(r, ord)
  where ord <= 40;

  return rid;
end;
$$;

-- Signup gate, checked by the caption app right after Google sign-in.
--   * superadmins and people who already finished onboarding always pass
--     (the gate is for new signups, it never locks out existing members)
--   * with no domains and no addresses configured, everyone passes
--   * otherwise: whitelisted address, or an allowed domain (subdomains count:
--     cs.columbia.edu matches columbia.edu)
create or replace function public.signup_allowed()
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  em  text := lower(auth.email());
  dom text := split_part(lower(auth.email()), '@', 2);
begin
  if auth.uid() is null or em is null then
    return false;
  end if;
  if public.is_superadmin() then
    return true;
  end if;
  if exists (select 1 from public.profiles p
             where p.id = auth.uid() and p.first_name is not null and p.last_name is not null) then
    return true;
  end if;
  if not exists (select 1 from public.allowed_signup_domains)
     and not exists (select 1 from public.whitelisted_emails) then
    return true;
  end if;
  return exists (select 1 from public.whitelisted_emails w where w.email = em)
      or exists (select 1 from public.allowed_signup_domains d
                 where dom = d.domain or dom like '%.' || d.domain);
end;
$$;

